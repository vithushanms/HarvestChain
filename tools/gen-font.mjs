export const KEYS = ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_'.split('').concat(['STAR', 'UP', 'DOWN']);

function pack(glyphs, w, h) {
  const nbytes = Math.ceil(w * h / 8);
  const out = [];
  for (const k of KEYS) {
    const rows = (glyphs[k] ?? Array(h).fill('.'.repeat(w)).join('/')).split('/');
    if (rows.length !== h || rows.some((r) => r.length !== w)) throw new Error(`bad glyph ${k}: ${rows}`);
    const bytes = Array(nbytes).fill(0);
    rows.forEach((row, y) => [...row].forEach((c, x) => {
      if (c === '#') { const n = y * w + x; bytes[n >> 3] |= 1 << (n & 7); }
    }));
    out.push(bytes);
  }
  return out;
}
export const bodyBytes = () => pack(BODY, 5, 7);
export const badgeBytes = () => pack(BADGE, 3, 5);

export function generate() {
  const seg = (addr, glyphs, name) => {
    let t = `(data (i32.const 0x${addr.toString(16)})\n`;
    glyphs.forEach((g, i) => {
      const label = i < 64 ? JSON.stringify(String.fromCharCode(32 + i)).slice(1, -1) : KEYS[i].toLowerCase();
      t += `  "${esc(g)}" ;; ${i} ${label.replace(/\\/g, '\\\\')}\n`;
    });
    return t + `) ;; ${name}\n`;
  };
  return seg(BODY_ADDR, bodyBytes(), 'font 5x7') + seg(BADGE_ADDR, badgeBytes(), 'font 3x5');
}

if (isMain(import.meta)) splice('fonts', generate());
